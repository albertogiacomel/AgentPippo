'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const values=new Map();
const context=vm.createContext({console,localStorage:{getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)},NodeFilter:{SHOW_TEXT:4},document:{documentElement:{},title:'Agente Pippo',body:{},querySelector:()=>({textContent:'',isConnected:true}),createTreeWalker:()=>({nextNode:()=>false}),querySelectorAll:()=>[]}});
for(const file of ['engine.js','en.js','en_ui.js','vehicles.js','content.js','i18n.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../dist',file),'utf8'),context,{filename:file});
const E=context.PortoBuffo,I=context.PippoI18n;
I.update({language:'en'});
for(const chapter of E.cases){for(const key of ['title','type','brief','intro','goal','ending'])if(chapter[key])assert.notEqual(I.t(chapter[key]),chapter[key],key);for(const hint of chapter.hints)assert.notEqual(I.t(hint),hint);}
for(const place of E.places)assert.notEqual(I.t(place),place);
assert.equal(I.t(I.format('locked',3)),'Solve 3 cases first');
assert.equal(I.t('Una parola con Guarda dentro'),'Una parola con Guarda dentro','No substring substitution');
const label={textContent:'',isConnected:true};I.text(label,'Impostazioni');assert.equal(label.textContent,'Settings');
assert.equal(I.t('Impostazioni'),'Settings');
I.update({language:'it',sounds:false,difficulty:'easy'});
assert.equal(I.t('Impostazioni'),'Impostazioni');
assert.equal(label.textContent,'Impostazioni','Live bindings revert without reverse translation');
assert.equal(JSON.parse(values.get('agent_pippo_settings')).difficulty,'easy');
const s=E.initialState();s.hintLevel=1;
I.update({language:'en'});
for(const c of E.cases){assert.equal(I.t(c.intro+' '+c.brief),I.t(c.intro)+' '+I.t(c.brief));assert.equal(I.t(c.ending+' Hai guadagnato 5 stelle!'),I.t(c.ending)+' You earned 5 stars!');}
assert.equal(I.t('Non hai ancora trovato lo spartito in piazza. Note suonate: nessuna'),'You have not found the sheet music in the square yet. Notes played: none');
I.update({language:'unknown',sounds:'no',difficulty:'invalid'});assert.equal(I.settings.language,'en');assert.equal(I.settings.difficulty,'easy');
const markup={isConnected:true,textContent:'',replaceChildren(){this.textContent='';}};I.text(markup,'Impostazioni');I.clearText(markup);markup.textContent='SVG';I.update({language:'it'});assert.equal(markup.textContent,'SVG','Replacing text with illustrations removes its stale binding');
assert.equal(E.hintFor(s,'challenge'),E.cases[0].hints[0]);
assert.equal(E.hintFor(s,'easy'),E.cases[0].hints[2]);
s.caseIndex=1;s.room=1;s.sequence=['sun'];
assert.equal(E.answer(s,'melody','star','easy').ok,false);assert.equal(s.sequence.length,1);
assert.equal(E.answer(s,'melody','star','normal').ok,false);assert.equal(s.sequence.length,0);
console.log('PASS: English chapter/hint catalog, composed labels, persisted preferences and difficulty rules.');
